public class Data1 {
    public static void main(String[] args) {
    int age = 14;
    int grade = 9;
    double quotient = (age * 2) / grade;
    int remainder = (age * 2) % grade;
    System.out.println("Sum: " + (age + grade));
    System.out.println("Product: " + (age * grade));
    System.out.println("Difference: " + (age - grade));
    System.out.println("Quotient: " + quotient);
    System.out.println("Remainder: " + remainder);
    }
}
